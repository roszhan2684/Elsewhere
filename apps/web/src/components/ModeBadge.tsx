export function ModeBadge({ mode }: { mode: "live" | "mock" }) {
  if (mode === "live") {
    return (
      <span className="inline-flex items-center gap-1.5 rounded-full border border-line-2 px-2.5 py-1 font-mono text-[10px] uppercase tracking-[0.1em] text-paper-2">
        <span className="h-1.5 w-1.5 rounded-full bg-[#5fd38d]" aria-hidden="true" />
        Live · Meta models
      </span>
    );
  }
  return (
    <span
      className="inline-flex items-center gap-1.5 rounded-full border border-dashed border-line-2 px-2.5 py-1 font-mono text-[10px] uppercase tracking-[0.1em] text-muted"
      title="No Meta API key is configured on the server, so a scripted offline model stands in. Nothing here was generated by Meta models."
    >
      <span className="h-1.5 w-1.5 rounded-full bg-muted" aria-hidden="true" />
      Offline mock
    </span>
  );
}
